import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const packageRoot = resolve(import.meta.dirname, "../packages/player");
const styleRoot = resolve(packageRoot, "src/view/styles");
const outputPath = resolve(styleRoot, "player-styles.generated.ts");
const sourcePaths = [
  "tokens.css",
  "base.css",
  "typography.css",
  "karaoke.css",
  "content-region-control.css",
];

const sourceText = await Promise.all(
  sourcePaths.map((name) => readFile(resolve(styleRoot, name), "utf8")),
);
const cssText = sourceText
  .map((text) => text.trim())
  .filter(Boolean)
  .join("\n\n");
const generated = [
  "// Generated by scripts/generate-player-styles.mjs. Do not edit directly.",
  `export const playerStyleText = ${JSON.stringify(cssText)};`,
  "",
].join("\n");

let current = "";
try {
  current = await readFile(outputPath, "utf8");
} catch {
  // The first build creates the generated module.
}
if (current !== generated) await writeFile(outputPath, generated, "utf8");
